"""후속 질문 감지 — 이번 입력이 앞 대화가 있어야 뜻이 통하는 말인지 코드로 가른다.

판정은 전부 규칙이다. 모델에게 묻지 않는다(루트 §3). 참이면 pipeline 이 최근 대화를 조회해
Supervisor 에 넘기고, 거짓이면 조회 없이 지금처럼 이번 문장만 본다.

기울기는 놓침을 줄이는 쪽이다. 오탐은 조회 한 번과 토큰이 늘 뿐이고 Supervisor 가 앞 대화를
무시할 수 있다. 놓침은 앞 대화 없이 처리되는 지금 동작 그대로라 손해가 더 크다.

- 강한 표현은 앞 대화를 직접 가리키므로 주제어가 있어도 후속이다("앞에서 말한 간식 말고 …").
  "아까" · "방금" 은 대화 동사(추천 · 알려 · 말한 …)가 두 어절 안에 붙을 때만 강하다 —
  "아까 약 먹였어" 같은 기록 입력마다 앞 대화가 붙지 않게.
- 약한 표현("다른 건" · "더 쉬운" · "그거")은 주제어(간식 · 놀이 · 책 …)가 하나도 없을 때만
  후속이다. "다른 실내 놀이 추천해줘" 는 혼자 읽어도 뜻이 통한다.

로그는 남기지 않는다. 부르는 쪽이 감지 여부만 남긴다(원문 없이).
"""

import re

_STRONG = tuple(
    re.compile(pattern)
    for pattern in (
        # 시간 말 뒤 두 어절 안에 "추천 · 알려줘 · 말한 · 보여줘" 꼴이 붙을 때. 사이에 주어
        # ("선생님이")가 끼면 앞 대화를 가리키는 말이 아니라 남이 한 말을 전하는 기록이다
        r"(아까|방금|앞에서|좀 ?전에)\s?(?:\S*[^\s이가은는]\s){0,2}?"
        r"\S*?(추천|알려 ?(?:준|줬|줘)|말(?:한|했)|말해 ?줘|물어 ?(?:본|봤)|보여 ?(?:준|줬|줘))",
        r"그 ?중(?!요|간)",
        r"못 ?알려",
        # "두 번째는?" · "두 번째 거" — "두 번째 이가 났어" 같은 순서 말은 앞 대화를 가리키지 않는다
        r"(첫|두|세|네|다섯) ?번째 ?((거|건|걸|것|꺼)(?=\s|$|[?.!,]|로|요|야)|는|요|\?|$)",
    )
)

_WEAK = tuple(
    re.compile(pattern)
    for pattern in (
        # 낱말 처음에서만 — "먹이거나" · "아이건강" 의 "이거" · "이건" 을 세지 않는다
        r"(?:^|\s)그(거|건|걸|것)",
        r"(?:^|\s)이(거|건|걸|것)",
        r"다른 ?(거|건|걸|것|데|방법)",
        r"비슷한",
        r"더 ?(쉬운|어려운|간단한|짧은|추천|알려|없)",
        r"또 ?(뭐|다른|있)",
        r"다시 ?(알려|말해|추천|보여)",
        r"^(그럼|그러면)(?!서)",
    )
)

# 요청의 주제를 스스로 밝히는 낱말. 있으면 약한 표현만으로는 후속으로 보지 않는다
_TOPICS = (
    "간식",
    "밥",
    "메뉴",
    "반찬",
    "식단",
    "이유식",
    "도시락",
    "음식",
    "요리",
    "놀이",
    "나들이",
    "체험",
    "장소",
    "책",
    "동화",
    "공부",
    "한글",
    "숫자",
    "영어",
    "습관",
    "양치",
    "낮잠",
    "배변",
    "병원",
    "소아과",
    "검진",
    "접종",
    "몸무게",
    "일정",
    "준비물",
)


def looks_like_followup(text: str) -> bool:
    """앞 대화가 있어야 뜻이 통하는 입력으로 보이면 True."""
    normalized = re.sub(r"\s+", " ", text).strip()
    if not normalized:
        return False
    if any(pattern.search(normalized) for pattern in _STRONG):
        return True
    if any(topic in normalized for topic in _TOPICS):
        return False
    return any(pattern.search(normalized) for pattern in _WEAK)
