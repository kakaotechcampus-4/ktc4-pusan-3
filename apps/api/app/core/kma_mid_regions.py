def region_of(grid: WeatherGrid) -> str:
    """격자에서 가장 가까운 대표 지점의 중기 육상예보 구역."""
    _, _, region = min(
        GRID_REGIONS, key=lambda row: (row[0] - grid.nx) ** 2 + (row[1] - grid.ny) ** 2
    )
    return region
