"""평가 표현 — 또래 비교 · 발달 판정은 거르고, 같은 글자가 든 평범한 문장은 통과시킨다."""

import pytest

from app.rules.evaluative import EVALUATIVE_PHRASES, find_evaluative


@pytest.mark.parametrize(
    "text",
    [
        "또래보다 블록을 잘 쌓아요",
        "또래에 비해 말이 빨라요",
        "평균보다 오래 집중했어요",
        "정상 발달 범위예요",
        "발달이 늦은 편이라 도움이 돼요",
        "소근육 발달 단계에 맞는 놀이",
        "그림에 재능이 있어요",
        "문제 행동을 줄여 줘요",
        "뛰어난 집중력",
        "영어 말하기에 소질이 있어요",
        # #195 리뷰 — 사이에 말이 끼거나 낱말로 못 잡던 모양
        "또래 아이들보다 말이 빨라요",
        "다른 아이들보다 블록을 잘 쌓아요",
        "다른 친구들에 비해 키가 커요",
        "또래 친구들과 비교하면 잘하는 편이에요",
        "걸음마가 늦어요",
        "말이 조금 느린 것 같아요",
        "키가 작은 편이에요",
        "백분위 30",
        "상위 10% 안에 들어요",
        "하위 5%",
        "성장곡선 아래쪽이에요",
        "성장이 정체됐어요",
        "체중이 부족해요",
    ],
)
def test_평가_표현을_잡는다(text):
    assert find_evaluative(text)


@pytest.mark.parametrize(
    "text",
    [
        "늦은 오후에 공원 산책",
        "느리게 걷기 놀이",
        "산 정상까지 걸어가기",
        "또래 친구와 공놀이",
        "밖으로 뛰어나가 비눗방울 잡기",
        "평소처럼 블록 쌓기",
        "문제 풀이 대신 그림 그리기",
        "느린 편지 보내기",
        "주말 늦은 오후 산책",
        "또래 친구와 공놀이",
        "다른 친구와 함께 블록 쌓기",
        "콩나물이 잘 크고 있어요",
        "식물 성장 관찰하기",
        "재료가 부족하면 종이컵으로 바꿔요",
        "끝까지 해냈어요",
        "오래 집중해서 탑을 쌓았어요",
        "편의점 놀이",
    ],
)
def test_같은_글자가_든_평범한_문장은_통과한다(text):
    """RAG_plan 의 한 글자 어간(늦 · 느리 · 정상)을 그대로 걸면 이런 문장이 거절된다."""
    assert find_evaluative(text) == ()


def test_공백은_무시한다():
    assert find_evaluative("또래 보다 잘해요") == ("또래보다",)
    assert find_evaluative("백 분 위") == ("백분위",)


def test_칭찬은_막지_않고_능력_꼬리표만_막는다():
    """긍정 평가도 판정이다 — 관찰 몇 건으로 "소질"이라 하면 기록보다 크게 말한다."""
    assert find_evaluative("영어 말하기를 좋아해요") == ()
    assert find_evaluative("영어 말하기에 소질이 있어요")


def test_목록에_중복이_없다():
    dense = ["".join(p.split()) for p in EVALUATIVE_PHRASES]
    assert len(dense) == len(set(dense))
