"""급식표 한 구간이 덜 읽혔는지 — 평일 수는 코드가 센다 (루트 CLAUDE.md §3 날짜 계산).

급식표는 1~15일 · 16~말일 두 호출로 읽는다. 한 호출이 16일 하나만 내고 정상 종료(`stop`)한 적이
있다(2026-11-11 실측) — 오류가 아니라 "읽지 못했어요" 줄이 나가지 않고, 21일치 중 11일치만 조용히
저장됐다. 그래서 읽은 날 수를 그 구간의 평일 수와 견준다.

- 덜 읽힘: 읽은 날 × 2 < 평일 수 (평일의 절반에 못 미친다)
- 🚨 다른 구간이 충분히(평일의 3/4 이상) 읽혔을 때만 알린다 — 한 주치 · 두 주치 식단표에서
  뜨지 않게.
- 호출이 실패한 구간은 이미 "읽지 못했어요" 줄이 나갔다 — 겹쳐 내지 않고, 다른 구간의 근거로도
  쓰지 않는다.

날짜는 지어낸 것이다. 실제 기관 문서는 쓰지 않는다.
"""

import pytest

from app.rules.meal_plan_coverage import ThinRange, thin_ranges, weekdays_between

RANGES = ((1, 15), (16, 31))
# 2026-11: 1일이 일요일 — 평일은 1~15일에 10일, 16~30일에 11일
NOV_FRONT = (2, 3, 4, 5, 6, 9, 10, 11, 12, 13)
NOV_BACK = (16, 17, 18, 19, 20, 23, 24, 25, 26, 27, 30)


@pytest.mark.parametrize(
    ("year", "month", "first", "last", "expected"),
    [
        (2026, 11, 1, 15, 10),
        (2026, 11, 16, 31, 11),  # 말일(30일)에서 자른다
        (2025, 1, 1, 15, 11),
        (2025, 1, 16, 31, 12),
        (2026, 2, 16, 31, 10),  # 2월은 28일(토요일)까지
    ],
)
def test_평일은_그_달의_달력으로_말일까지_센다(year, month, first, last, expected) -> None:
    assert weekdays_between(year, month, first, last) == expected


def test_뒤_구간에서_하루만_읽으면_그_구간이_덜_읽혔다() -> None:
    # 실측 모양: 앞 10일 다 읽고 뒤는 16일 하나만 내고 정상 종료
    assert thin_ranges(2026, 11, RANGES, (*NOV_FRONT, 16)) == (ThinRange(16, 30, 1, 11),)


def test_정상_한_달은_알리지_않는다() -> None:
    assert thin_ranges(2026, 11, RANGES, NOV_FRONT + NOV_BACK) == ()


def test_휴일이_며칠_껴도_절반이_넘으면_알리지_않는다() -> None:
    # 설 연휴처럼 평일 사흘이 비어도 뒤 구간 11일 중 8일을 읽었다
    assert thin_ranges(2026, 11, RANGES, NOV_FRONT + NOV_BACK[:8]) == ()


def test_방학처럼_한_구간에_급식이_실제로_적어도_다른_구간이_다_읽혔으면_알린다() -> None:
    # 2025-08: 앞 구간 평일 11일 중 방학 · 광복절로 급식은 5일(1 · 11~14일)뿐. 휴일을 표에 적지
    # 않은 급식표면 진짜 누락과 구별할 수 없다 — 알린다. 보호자는 사진과 비교해 방학인 것을 본다
    # (되돌릴 수 있는 확인 한 줄). 휴일을 표에 적었으면 그 날도 읽은 날이라 알리지 않는다(agents).
    back = (18, 19, 20, 21, 22, 25, 26, 27, 28, 29)
    assert thin_ranges(2025, 8, RANGES, (1, 11, 12, 13, 14, *back)) == (ThinRange(1, 15, 5, 11),)


def test_한_주치_식단표는_알리지_않는다() -> None:
    # 한 주(평일 5일 + 토요일)는 어느 구간에서도 평일의 3/4 을 넘지 못한다 — 근거가 못 된다
    assert thin_ranges(2026, 11, RANGES, (9, 10, 11, 12, 13)) == ()
    assert thin_ranges(2026, 11, RANGES, (16, 17, 18, 19, 20, 21)) == ()
    assert thin_ranges(2026, 11, RANGES, (12, 13, 14, 16, 17)) == ()  # 두 구간에 걸친 한 주


def test_두_구간에_걸친_두_주치도_알리지_않는다() -> None:
    assert thin_ranges(2026, 11, RANGES, (9, 10, 11, 12, 13, 16, 17, 18, 19, 20)) == ()


def test_보름치_식단표는_빈_구간을_한_줄로_알린다() -> None:
    # 1~15일만 있는 급식표와 뒤 호출이 아무것도 내지 않은 한 달 표는 출력으로 구별할 수 없다.
    # 조용히 반달이 빠지는 쪽이 더 나빠서 알린다 — 읽은 날이 0 이다(화면 문구가 다르다, agents)
    assert thin_ranges(2026, 11, RANGES, NOV_FRONT) == (ThinRange(16, 30, 0, 11),)


def test_호출이_실패한_구간은_겹쳐_알리지_않는다() -> None:
    # 뒤 호출 실패 → 이미 "16일~30일 급식은 읽지 못했어요" 줄이 나갔다
    assert thin_ranges(2026, 11, RANGES, NOV_FRONT, failed=((16, 31),)) == ()


def test_실패한_구간은_다른_구간을_알릴_근거가_못_된다() -> None:
    # 앞 호출 실패 + 뒤 구간 하루 — 한 달 표인지 알 수 없다. 화면엔 이미 "읽지 못했어요" 가 있다
    assert thin_ranges(2026, 11, RANGES, (16,), failed=((1, 15),)) == ()


def test_구간이_하나뿐이면_견줄_곳이_없어_알리지_않는다() -> None:
    assert thin_ranges(2026, 11, ((1, 31),), (2,)) == ()
    assert thin_ranges(2026, 11, (), (2,)) == ()


def test_구간_밖의_날과_주말은_평일_수에_넣지_않지만_읽은_날로는_센다() -> None:
    # 토요일 급식이 있는 기관 — 읽은 날이다. 뒤 구간에서 토요일 이틀만 읽혀도 덜 읽힌 것이다
    assert thin_ranges(2026, 11, RANGES, (*NOV_FRONT, 21, 28)) == (ThinRange(16, 30, 2, 11),)
