def test_증상처럼_보이는_행동은_닫는다(text):
    assert closure_key([text]) == "closed.symptom_habit"


def test_측정_요약():
    closed = [t for t in NOT_CLOSED if closure_key([t])]
    missed = [t for t in (*CLOSED_MEDICAL, *CLOSED_SYMPTOM) if not closure_key([t])]
    assert (len(NOT_CLOSED), len(closed)) == (41, 2)
    assert (len(CLOSED_MEDICAL) + len(CLOSED_SYMPTOM), len(missed)) == (41, 0)
