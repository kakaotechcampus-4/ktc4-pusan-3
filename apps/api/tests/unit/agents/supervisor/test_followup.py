"""후속 질문 감지 규칙 — 앞 대화가 있어야 뜻이 통하는 입력만 고른다.

문장은 전부 지어낸 것이다. 후속이면 앞 대화를 조회해 Supervisor 에 넘기고, 아니면 지금처럼
이번 문장만 본다. 오탐은 조회 한 번이 늘 뿐이고 놓침은 지금 동작 그대로라
놓침을 줄이는 쪽으로 쓴다.
"""

import pytest

from app.agents.supervisor.followup import looks_like_followup

FOLLOWUPS = [
    "그럼 다른 건?",
    "더 쉬운 건 없어?",
    "그중 두 번째는?",
    "더 추천해줘",
    "아까 못 알려준 거 다시 알려줘",
    "아까 추천한 것보다 쉬운 건?",
    "방금 알려준 거 다시 보여줘",
    "그거 말고 다른 거",
    "비슷한 거 또 있어?",
    "다시 알려줘",
    "다른 방법도 알려줘",
    "그럼 어떻게 해?",
    "또 뭐 있어?",
    "두 번째 거 자세히 알려줘",
    "그건 몇 살부터 할 수 있어?",
    "앞에서 말한 간식 말고 다른 거",  # 강한 표현은 주제어가 있어도 후속
    "오늘 또 울었어. 다른 방법도 알려줘",  # 기록과 섞여도
    "이것보다 쉬운 거 있어?",
    "오늘 블록 쌓기 해 봤는데 어려워했어. 더 쉬운 거 있어?",
    "다른 데는 없어?",
    "좀 더 쉬운 건?",
    "두 번째는?",
    "이거 말고",
]
INDEPENDENT = [
    "오늘 간식 추천해줘",
    "아이랑 할 실내 놀이 알려줘",
    "다른 실내 놀이 추천해줘",
    "어제와 다른 간식 추천해줘",
    "우유 말고 다른 간식 추천해줘",
    "공룡 책 더 추천해줘",
    "아까 사과 반 개 먹었어",
    "방금 낮잠 깼어",
    "아까 약 먹였어",
    "오늘 블록 쌓기 했어",
    "주말에 갈 만한 나들이 장소 추천해줘",
    "양치 혼자 하게 하고 싶어",
    "내일 소풍 도시락은 뭐가 좋을까?",
    "지금 문 연 소아과 찾아줘",
    "잘 크고 있어?",
    "열이 38도야",
    "그 중요한 준비물 챙겼어",
    # 기록 입력 — 앞 대화를 붙이면 단발 요청처럼 흔들리고, 아직 모델에 안 간 말이 한 번 더 간다
    "아까 좀 아파 보여서 해열제 먹였어",
    "아까 친구 손을 물어서 혼났대",
    "방금 동생 팔을 물어뜯었어",
    "아까 처음으로 엄마라고 말해 줬어",
    "아까 선생님이 알려주셨는데 오늘 열났대",
    "그러면서 계속 울었어",
    "가는 그 중간에 잠들었어",
    # 낱말 중간 · 순서 말 — "먹이거나" 의 "이거", "두 번째 이" 는 앞 대화를 가리키지 않는다
    "고기를 먹이거나 말거나 했어",
    "두 번째 이가 났어",
    "세 번째 생일이야",
    "첫 번째 걸음마 했어",
]


@pytest.mark.parametrize("text", FOLLOWUPS)
def test_앞_대화가_있어야_뜻이_통하면_후속이다(text: str) -> None:
    assert looks_like_followup(text) is True


@pytest.mark.parametrize("text", INDEPENDENT)
def test_혼자_읽어도_뜻이_통하면_후속이_아니다(text: str) -> None:
    assert looks_like_followup(text) is False


def test_띄어쓰기가_달라도_같다() -> None:
    assert looks_like_followup("그 중 두번째는?") is looks_like_followup("그중 두 번째는?") is True


def test_빈_문장은_후속이_아니다() -> None:
    assert looks_like_followup("   ") is False
