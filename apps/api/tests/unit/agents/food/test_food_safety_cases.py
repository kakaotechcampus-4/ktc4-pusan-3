def test_여러_항목을_등록하면_각각_막는다() -> None:
    entries = _entries("우유", "땅콩")

    assert _judge(entries, _menu("크림수프", "우유")) == "blocked"
    assert _judge(entries, _menu("땅콩강정", "땅콩")) == "blocked"
    assert _judge(entries, _menu("현미밥", "현미")) == "passed"


def test_한_칸에_여러_이름을_적어도_각각_막는다() -> None:
    entries = _entries("새우, 게")

    assert _judge(entries, _menu("꽃게탕", "꽃게")) == "blocked"
    assert _judge(entries, _menu("새우볶음밥", "새우", "밥")) == "blocked"


def test_알레르기가_없으면_흔한_메뉴는_통과한다() -> None:
    for row in (
        _menu("현미밥", "현미"),
        _menu("된장국", "된장", "두부"),
        _menu("불고기", "소고기", "간장"),
    ):
        assert _judge([], row) == "passed"


def test_취소한_항목은_빼고_나머지는_막는다() -> None:
    entries = [
        SafetyEntry(kind="allergy", label="우유", status="active"),
        SafetyEntry(kind="allergy", label="땅콩", status="retracted"),
    ]

    assert _judge(entries, _menu("우유푸딩", "우유", "설탕")) == "blocked"
    assert _judge(entries, _menu("땅콩조림", "땅콩", "간장")) == "passed"


def test_메뉴명이_자모로_풀려_와도_막는다() -> None:
    name = unicodedata.normalize("NFD", "우유푸딩")

    assert _judge(_entries("우유"), _menu(name, "설탕")) == "blocked"


