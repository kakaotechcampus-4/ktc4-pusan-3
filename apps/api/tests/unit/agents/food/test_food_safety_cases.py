def _menu(name: str, *ingredients: str, resolved: bool = True) -> MenuCatalogRow:
    return MenuCatalogRow(
        menu_key=name,
        display_name=name,
        source="manual",
        resolved=resolved,
        synced_at=NOW,
        ingredients=ingredients,
    )


def _entries(*labels: str, kind: str = "allergy", status: str = "active") -> list[SafetyEntry]:
    return [SafetyEntry(kind=kind, label=label, status=status) for label in labels]  # type: ignore[arg-type]


def _judge(entries: list[SafetyEntry], row: MenuCatalogRow, months: int = OLDER) -> str:
    result = filter_food_safety([row], entries, "preschool", months=months)
    if result.blocked:
        return "blocked"
    return "unchecked" if result.unchecked else "passed"


